const { contextBridge, ipcRenderer } = require('electron');

// The renderer only sees these functions. It has no direct access to Node or Electron.
contextBridge.exposeInMainWorld('api', {
  listProfiles: () => ipcRenderer.invoke('profiles:list'),
  saveProfile: (input) => ipcRenderer.invoke('profiles:save', input),
  deleteProfile: (id) => ipcRenderer.invoke('profiles:delete', id),
  trashProfile: (id) => ipcRenderer.invoke('profiles:trash', id),
  restoreProfile: (id) => ipcRenderer.invoke('profiles:restore', id),
  purgeProfile: (id) => ipcRenderer.invoke('profiles:purge', id),
  listTrash: () => ipcRenderer.invoke('profiles:trash-list'),
  duplicateProfile: (id) => ipcRenderer.invoke('profiles:duplicate', id),
  batchUpdate: (ids, patch) => ipcRenderer.invoke('profiles:batch-update', ids, patch),
  exportProfiles: (ids) => ipcRenderer.invoke('profiles:export', ids),
  importProfiles: () => ipcRenderer.invoke('profiles:import'),
  clearCookies: (id) => ipcRenderer.invoke('profiles:clear-cookies', id),
  launchProfile: (id) => ipcRenderer.invoke('profiles:launch', id),
  stopProfile: (id) => ipcRenderer.invoke('profiles:stop', id),
  listProxies: () => ipcRenderer.invoke('proxies:list'),
  saveProxy: (input) => ipcRenderer.invoke('proxies:save', input),
  deleteProxy: (id) => ipcRenderer.invoke('proxies:delete', id),
  listKernels: () => ipcRenderer.invoke('kernels:list'),
  listMajors: (kernel) => ipcRenderer.invoke('browsers:majors', kernel),
  listBrowserVersions: (kernel) => ipcRenderer.invoke('browsers:versions', kernel),
  listInstalledBuilds: (kernel) => ipcRenderer.invoke('browsers:installed', kernel),
  removeBuild: (kernel, version) => ipcRenderer.invoke('browsers:remove', kernel, version),
  buildStats: () => ipcRenderer.invoke('browsers:stats'),
  removeAllBuilds: (kernel) => ipcRenderer.invoke('browsers:remove-all', kernel),
  parseProxy: (text, defaultType) => ipcRenderer.invoke('proxy:parse', text, defaultType),
  checkProxy: (proxy) => ipcRenderer.invoke('proxy:check', proxy),
  getSettings: () => ipcRenderer.invoke('settings:get'),
  setSettings: (patch) => ipcRenderer.invoke('settings:set', patch),
  resetSettings: () => ipcRenderer.invoke('settings:reset'),
  appInfo: () => ipcRenderer.invoke('app:info'),
  openExternal: (url) => ipcRenderer.invoke('shell:open-external', url),
  openPath: (target) => ipcRenderer.invoke('shell:open-path', target),
  openDataDir: () => ipcRenderer.invoke('shell:open-data-dir'),
  onChange: (callback) => ipcRenderer.on('profiles:changed', () => callback()),
  onBrowserProgress: (callback) => ipcRenderer.on('browsers:progress', (_e, progress) => callback(progress)),
});
